// Generates src/icons.js from Lucide SVGs: node tools/icons.mjs <lucide/icons dir>
import fs from "node:fs";
import path from "node:path";
const dir = process.argv[2];
const names = fs.readFileSync(new URL("./icons.txt", import.meta.url), "utf8").split(/\s+/).filter(Boolean);
const out = ["// Icons from Lucide (ISC License, https://lucide.dev). Generated by tools/icons.mjs.", "export const ICONS = {"];
const missing = [];
for (const n of names) {
  const file = path.join(dir, `${n}.svg`);
  if (!fs.existsSync(file)) {
    missing.push(n);
    continue;
  }
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(fs.readFileSync(file, "utf8"))[1]
    .split("\n")
    .map((l) => l.trim())
    .join("")
    .replace(/\s*\/>/g, "/>");
  out.push(`${JSON.stringify(n)}: ${JSON.stringify(inner)},`);
}
out.push("};", "");
fs.writeFileSync(new URL("../src/icons.js", import.meta.url), out.join("\n"));
if (missing.length) console.log("missing:", missing.join(" "));
console.log(`${names.length - missing.length} icons`);
